#!/usr/bin/env python3
"""Regenerate the desktop's 16px Chinese glyph subset from Noto Sans CJK SC."""
import argparse
from pathlib import Path
from PIL import ImageFont

src = Path(__file__).resolve().parent / "src"
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("font", help="NotoSansCJK-Regular.ttc")
args = parser.parse_args()
font = ImageFont.truetype(args.font, 16, index=2)  # Simplified Chinese face
chars = sorted({ord(c) for c in (src / "desktop.cc").read_text(encoding="utf8")
                if 0x4e00 <= ord(c) <= 0x9fff})
bitmap = bytearray()
glyphs = ["    {0},"]
for code in chars:
    char = chr(code)
    mask, (x, y) = font.getmask2(char, mode="L", anchor="ls")
    w, h = mask.size
    glyphs.append(f"    {{{len(bitmap)}, 256, {w}, {h}, {x}, {-y-h}}}, /* {char} */")
    pixels = list(mask)
    pixels.append(0)
    bitmap.extend((pixels[i] & 0xf0) | (pixels[i+1] >> 4) for i in range(0, w*h, 2))

def rows(values, count):
    return "\n".join("    " + ", ".join(map(str, values[i:i+count])) + ","
                     for i in range(0, len(values), count))

(src / "desktop_font.c").write_text(f"""/* Generated by mkfont.py. Noto Sans CJK SC subset, see FONT-LICENSE. */
#include "lvgl/lvgl.h"
static const uint8_t bitmap[] = {{
{rows(bitmap, 20)}
}};
static const lv_font_fmt_txt_glyph_dsc_t glyphs[] = {{
{chr(10).join(glyphs)}
}};
static const uint16_t offsets[] = {{
{rows([c-chars[0] for c in chars], 12)}
}};
static const lv_font_fmt_txt_cmap_t map = {{
    .range_start = {chars[0]}, .range_length = {chars[-1]-chars[0]+1}, .glyph_id_start = 1,
    .unicode_list = offsets, .list_length = {len(chars)}, .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY
}};
static const lv_font_fmt_txt_dsc_t desc = {{
    .glyph_bitmap = bitmap, .glyph_dsc = glyphs, .cmaps = &map, .cmap_num = 1, .bpp = 4
}};
const lv_font_t desktop_font = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt, .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = 20, .base_line = 4, .dsc = &desc, .fallback = &lv_font_montserrat_14
}};
""", encoding="utf8")
